export function findOptimalRitualWindow(date, targetPlanet, daysRange = 7) {
  const windows = [];
  const startDate = new Date(date);

  for (let i = 0; i < daysRange; i++) {
    const checkDate = new Date(startDate);
    checkDate.setDate(checkDate.getDate() + i);

    const dayPlanetOrder = ['Sol', 'Luna', 'Marte', 'Mercurio', 'Júpiter', 'Venus', 'Saturno'];
    const dayPlanet = dayPlanetOrder[checkDate.getDay()];

    const planetHours = getPlanetaryHourForDate(checkDate, targetPlanet);

    for (const ph of planetHours) {
      const hourStart = new Date(checkDate);
      hourStart.setHours(ph.start, 0, 0, 0);
      const hourEnd = new Date(checkDate);
      hourEnd.setHours(ph.end, 0, 0, 0);

      let score = 50;
      if (dayPlanet === targetPlanet) score += 20;
      if (checkDate.getDay() === 0 && targetPlanet === 'Sol') score += 15;
      if (checkDate.getDay() === 1 && targetPlanet === 'Luna') score += 15;
      if (checkDate.getDay() === 2 && targetPlanet === 'Marte') score += 15;
      if (checkDate.getDay() === 3 && targetPlanet === 'Mercurio') score += 15;
      if (checkDate.getDay() === 4 && targetPlanet === 'Júpiter') score += 15;
      if (checkDate.getDay() === 5 && targetPlanet === 'Venus') score += 15;
      if (checkDate.getDay() === 6 && targetPlanet === 'Saturno') score += 15;

      windows.push({
        date: checkDate.toLocaleDateString('es-ES', { day: 'numeric', month: 'long' }),
        hourStart: `${ph.start}:00`,
        hourEnd: `${ph.end}:00`,
        dayPlanet,
        hourPlanet: ph.planet,
        score: Math.min(100, score),
        isOptimal: score >= 70
      });
    }
  }

  windows.sort((a, b) => b.score - a.score);
  return windows.slice(0, 5);
}
